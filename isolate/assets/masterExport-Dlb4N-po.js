function colRef(index) {
  let n = index;
  let out = "";
  while (n > 0) {
    const rem = (n - 1) % 26;
    out = String.fromCharCode(65 + rem) + out;
    n = Math.floor((n - 1) / 26);
  }
  return out;
}
function addAlertSheet(wb, o, name, kind) {
  const keys = kind === "surveillance" ? [
    "facility",
    "block",
    "phc",
    "survDue1",
    "surv1",
    "survDue2",
    "surv2",
    "recertStatus"
  ] : kind === "noc" ? ["facility", "block", "phc", "nocAvailable", "nocStatus", "nocCertified", "nocValidity", "nocDoc"] : ["facility", "block", "phc", "gapAmount", "gcYear", "procLink"];
  const cols = keys.map((k) => o.columns.find((c) => c.key === k)).filter((c) => !!c);
  if (cols.length === 0) return;
  const ws = wb.addWorksheet(name, {
    pageSetup: {
      orientation: "landscape",
      fitToPage: true,
      fitToWidth: 1,
      fitToHeight: 0,
      printTitlesRow: "1:1"
    }
  });
  const head = ws.addRow(cols.map((c) => o.labels[c.key] ?? c.label));
  head.height = 28;
  head.eachCell((cell) => {
    cell.font = { bold: true, color: { argb: "FFFFFFFF" } };
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF0F6B63" } };
    cell.alignment = { vertical: "middle", wrapText: true };
    cell.border = thinBorder;
  });
  for (const r of o.rows) {
    const line = cols.map((c) => cellText(r, c.key) || "-");
    if (line.every((v) => v === "-")) continue;
    ws.addRow(line);
  }
  cols.forEach((c, i) => {
    ws.getColumn(i + 1).width = widthFor(c);
  });
}

