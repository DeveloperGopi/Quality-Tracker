export type QuarterTemplateFacility = {
  name: string;
  block: string;
  phc: string;
  facilityType: string;
  /** The master NIN; blank rows stay blank so they can be filled by hand. */
  ninNumber?: string | null;
};

// The NEW NIN format (section 1). The Eco-Friendly Scorecard remains retired.
export const TEMPLATE_HEADERS = [
  "S. No",
  "NIN Number",
  "Block",
  "PHC",
  "Name of the facility",
  "Type",
  "Financial Year",
  "Quarter",
  "NQAS IA Score",
  "Kayakalp IA Score",
] as const;

const LOCKED_FILL: ExcelJS.Fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFE8EFF2" } };

/**
 * The quarterly template the district DOWNLOADS (section 2.5): every facility
 * in scope, NIN as TEXT, the identity columns shaded + locked, the two score
 * columns validated 0–100 with an input message, a Lists sheet and a six-step
 * Instructions sheet. A plain CSV version is built by `buildIaTemplateCsv`.
 */
export function buildQuarterTemplateWorkbook(
  fy: string,
  q: 1 | 2 | 3 | 4,
  facilities: readonly QuarterTemplateFacility[],
): ExcelJS.Workbook {
  const wb = new ExcelJS.Workbook();
  wb.creator = "NQAS Tracker";
  wb.created = new Date();
  const label = formatFyQuarter(fy, q);
  const ws = wb.addWorksheet("IA scores", {
    views: [{ state: "frozen", ySplit: 1 }],
    pageSetup: { orientation: "landscape", fitToPage: true, fitToWidth: 1, fitToHeight: 0 },
  });
  ws.columns = [6, 16, 18, 20, 30, 10, 13, 9, 15, 17].map((w) => ({ width: w }));
  const head = ws.addRow([...TEMPLATE_HEADERS]);
  styleHeader(head);
  ws.pageSetup.printTitlesRow = "1:1";
  ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: TEMPLATE_HEADERS.length } };

  facilities.forEach((f, i) => {
    const row = ws.addRow([
      i + 1,
      f.ninNumber ?? "",
      f.block,
      f.phc,
      f.name,
      f.facilityType,
      fy,
      `Q${q}`,
      "",
      "",
    ]);
    row.alignment = { vertical: "middle" };
    // NIN is TEXT — a leading zero must survive Excel's number handling.
    row.getCell(2).numFmt = "@";
    // Identity columns are locked and shaded; only the two score cells are
    // editable, so a template can never be re-purposed as a facility edit.
    for (let c = 1; c <= 8; c++) {
      const cell = row.getCell(c);
      cell.protection = { locked: true };
      cell.fill = LOCKED_FILL;
    }
    // A facility with no stored NIN keeps an editable cell so the district can
    // fill it; an existing NIN stays locked like the other identity columns.
    if (!f.ninNumber) row.getCell(2).protection = { locked: false };
    for (const col of [9, 10]) {
      const cell = row.getCell(col);
      cell.protection = { locked: false };
      cell.dataValidation = {
        type: "decimal",
        operator: "between",
        formulae: [0, 100],
        allowBlank: true,
        showErrorMessage: true,
        errorTitle: "Score 0–100",
        error: "Enter a number from 0 to 100, a remark such as “New PHC”, or leave it blank.",
        showInputMessage: true,
        promptTitle: "IA score",
        prompt: "0–100. Blank means not reported — it is never saved as 0.",
      };
    }
  });

  // No password: the sheet is protected against accidental column edits only.
  ws.protect("", {
    selectLockedCells: true,
    selectUnlockedCells: true,
    formatCells: false,
    insertRows: false,
    deleteRows: false,
  });

  /* ---- Lists ---- */
  const lists = wb.addWorksheet("Lists");
  lists.columns = [{ width: 24 }, { width: 24 }, { width: 18 }];
  styleHeader(lists.addRow(["Facility types", "Financial years", "Quarters"]));
  const types = [...new Set(facilities.map((f) => f.facilityType))].sort();
  const fys = [...new Set([fy, previousFyLabel(fy), previousFyLabel(previousFyLabel(fy))])];
  for (let i = 0; i < Math.max(types.length, fys.length, 4); i++) {
    lists.addRow([types[i] ?? "", fys[i] ?? "", i < 4 ? `Q${i + 1}` : ""]);
  }

  /* ---- Instructions — six steps ---- */
  const notes = wb.addWorksheet("Instructions");
  notes.columns = [{ width: 110 }];
  const title = notes.addRow([`Quarter template — ${label}`]);
  title.font = { bold: true, size: 14 };
  for (const line of [
    "1. Fill ONLY the last two columns (NQAS IA Score, Kayakalp IA Score). The eight columns before them are locked.",
    "2. Format the NIN column as Text before typing (Format Cells → Text). Excel otherwise drops a leading zero or turns the NIN into 4.52732E+09.",
    "3. Scores are 0–100, whole or with decimals. 0 is a real score; leave the cell blank when the tracker was not reported.",
    "4. A remark may be typed instead of a score — e.g. “New PHC”, “Not assessed”, “Nil”. It is kept as a note, never as 0.",
    "5. Keep every row and the header exactly as they are. Facilities are matched by NIN, so the order of rows never matters.",
    "6. Save as .xlsx and upload it (or copy the two score columns into a paste). Nothing is written until you approve the preview.",
  ]) {
    const row = notes.addRow([line]);
    row.alignment = { wrapText: true, vertical: "top" };
  }
  return wb;
}

function previousFyLabel(fy: string): string {
  const start = Number(fy.slice(0, 4)) - 1;
  return `${start}-${String((start + 1) % 100).padStart(2, "0")}`;
}

export async function downloadIaQuarterTemplate(
  fy: string,
  q: 1 | 2 | 3 | 4,
  facilities: readonly QuarterTemplateFacility[],
): Promise<void> {
  const wb = buildQuarterTemplateWorkbook(fy, q, facilities);
  const buf = await wb.xlsx.writeBuffer();
  const blob = new Blob([buf], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `ia-quarter-template-${formatFyQuarter(fy, q).replace(/ /g, "-")}.xlsx`;
  a.click();
  URL.revokeObjectURL(url);
}

/** The plain CSV template (section 2.5) — same columns, same rows, UTF-8 BOM. */
export function buildIaTemplateCsv(
  fy: string,
  q: 1 | 2 | 3 | 4,
  facilities: readonly QuarterTemplateFacility[],
): string {
  const esc = (v: string): string => (/[",\r\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);
  const lines: string[] = [TEMPLATE_HEADERS.map(esc).join(",")];
  facilities.forEach((f, i) => {
    lines.push(
      [
        String(i + 1),
        esc(f.ninNumber ?? ""),
        esc(f.block),
        esc(f.phc),
        esc(f.name),
        esc(f.facilityType),
        fy,
        `Q${q}`,
        "",
        "",
      ].join(","),
    );
  });
  return `\uFEFF${lines.join("\r\n")}\r\n`;
}

export function downloadIaCsvTemplate(
  fy: string,
  q: 1 | 2 | 3 | 4,
  facilities: readonly QuarterTemplateFacility[],
): void {
  const csv = buildIaTemplateCsv(fy, q, facilities);
  const blob = new Blob([csv], { type: "text/csv;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `ia-quarter-template-${formatFyQuarter(fy, q).replace(/ /g, "-")}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

