export type IaQuarterReportRow = {
  facilityId: string;
  name: string;
  block: string;
  phc: string;
  facilityType: string;
  /** Score / remark / lock maps keyed by PERIOD: "<fy>|Q<q>". */
  scores: Record<string, Record<IaTracker, number | null>>;
  remarks: Record<string, Record<IaTracker, string | null>>;
  locked: Record<string, boolean>;
};

export type IaQuarterReportInput = {
  generatedBy: string;
  generatedAt: Date;
  /** The quarter this report is FOR (its label names the main sheet). */
  period: FyQuarter;
  /** Every period to show as a column group, ordered OLD → NEW. */
  periods: readonly FyQuarter[];
  rows: readonly IaQuarterReportRow[];
};

const periodKey = (p: FyQuarter): string => `${p.fy}|Q${p.q}`;

export function buildIaQuarterlyReportWorkbook(input: IaQuarterReportInput): ExcelJS.Workbook {
  const wb = new ExcelJS.Workbook();
  wb.creator = "NQAS Tracker";
  wb.created = input.generatedAt;
  const trackers = ALL_TRACKERS;
  const periods = input.periods;
  const periodLabels = periods.map((p) => formatFyQuarter(p.fy, p.q));
  const curLabel = formatFyQuarter(input.period.fy, input.period.q);
  const value = (
    f: IaQuarterReportRow,
    p: FyQuarter,
    t: IaTracker,
  ): string | number | null => {
    const s = f.scores[periodKey(p)]?.[t] ?? null;
    if (s != null) return s;
    const remark = f.remarks[periodKey(p)]?.[t] ?? null;
    return remark ?? null;
  };

  /* ---- Main sheet: one column per period per tracker ---- */
  const headers: (string | number)[] = ["S. No", "Facility", "Block", "PHC", "Type"];
  for (const pl of periodLabels) for (const t of trackers) headers.push(`${TRACKER_LABELS[t]} — ${pl}`);
  const widths: number[] = [6, 32, 18, 18, 8];
  for (let i = 0; i < periodLabels.length * trackers.length; i++) widths.push(14);
  addDataSheet(
    wb,
    curLabel,
    widths,
    headers,
    input.rows.map((f, i) => {
      const line: (string | number | null)[] = [i + 1, f.name, f.block, f.phc, f.facilityType];
      for (const p of periods) for (const t of trackers) line.push(value(f, p, t));
      return line;
    }),
  );

  /* ---- Summary ---- */
  const summary = wb.addWorksheet("Summary");
  summary.columns = [{ width: 34 }, { width: 60 }];
  const push = (label: string, val: string | number) => {
    const row = summary.addRow([label, val]);
    row.getCell(1).font = { bold: true };
  };
  const title = summary.addRow(["Internal Assessment Quarterly Report"]);
  title.font = { bold: true, size: 14 };
  push("Quarter", curLabel);
  push("Generated", toDisplayStamp(input.generatedAt.getTime()));
  push("Generated by", input.generatedBy);
  push("Facilities", input.rows.length);
  for (const t of trackers) {
    const reported = input.rows.filter((f) => f.scores[periodKey(input.period)]?.[t] != null).length;
    push(`${TRACKER_LABELS[t]} reported`, `${reported} of ${input.rows.length}`);
  }
  push("Locked rows", input.rows.filter((f) => f.locked[periodKey(input.period)]).length);

  /* ---- Quarter-over-quarter movement (first vs last period) ---- */
  if (periods.length >= 2) {
    const prev = periods[0];
    const cur = periods[periods.length - 1];
    const prevLabel = formatFyQuarter(prev.fy, prev.q);
    const curLabelQ = formatFyQuarter(cur.fy, cur.q);
    const movHeaders: (string | number)[] = ["Facility", "Block", "Type"];
    for (const t of trackers)
      movHeaders.push(
        `${TRACKER_LABELS[t]} ${prevLabel}`,
        `${TRACKER_LABELS[t]} ${curLabelQ}`,
        `${TRACKER_LABELS[t]} change`,
      );
    const movWidths: number[] = [32, 18, 8];
    for (let i = 0; i < trackers.length * 3; i++) movWidths.push(14);
    addDataSheet(
      wb,
      "Quarter-over-quarter",
      movWidths,
      movHeaders,
      input.rows.map((f) => {
        const line: (string | number | null)[] = [f.name, f.block, f.facilityType];
        for (const t of trackers) {
          const p = f.scores[periodKey(prev)]?.[t] ?? null;
          const c = f.scores[periodKey(cur)]?.[t] ?? null;
          const d =
            p != null && c != null ? Math.round((c - p) * 100) / 100 : null;
          line.push(
            p ?? f.remarks[periodKey(prev)]?.[t] ?? null,
            c ?? f.remarks[periodKey(cur)]?.[t] ?? null,
            d == null ? "■" : `${d > 0 ? "+" : ""}${d}`,
          );
        }
        return line;
      }),
    );
  }
  return wb;
}

export async function downloadIaQuarterlyReport(input: IaQuarterReportInput): Promise<void> {
  const wb = buildIaQuarterlyReportWorkbook(input);
  const buf = await wb.xlsx.writeBuffer();
  const blob = new Blob([buf], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `ia-quarterly-report-${formatFyQuarter(input.period.fy, input.period.q).replace(/ /g, "-")}.xlsx`;
  a.click();
  URL.revokeObjectURL(url);
}
