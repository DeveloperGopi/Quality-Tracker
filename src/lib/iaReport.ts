/**
 * IA REPORTS — the downloadables, all built on the ONE column model
 * (lib/iaPreviewColumns) so the workbook header is always above cell *i*:
 *
 *   downloadIaImportReport   — the import-history report of one batch
 *                              (Summary / Written / Not written sheets)
 *   downloadIaQuarterTemplate — the blank quarter sheet the district fills
 *   downloadIaQuarterlyReport — the IA Quarterly Report of stored quarters
 */

import ExcelJS from "exceljs";
import type { FyQuarter, IaPreviewState, IaTracker, IaPreviewRow } from "./iaImport";
import { formatFyQuarter, IA_TRACKERS, TRACKER_LABELS } from "./iaImport";
import { toDisplayStamp } from "./format";
import {
  iaColumnsForTrackers,
  iaPreviewCells,
  iaPreviewHeaders,
  IA_STATE_LABELS,
} from "./iaPreviewColumns";

const PRIMARY = "FF0D6960";
const headerFill: ExcelJS.Fill = { type: "pattern", pattern: "solid", fgColor: { argb: PRIMARY } };

function styleHeader(row: ExcelJS.Row): void {
  row.font = { bold: true, color: { argb: "FFFFFFFF" }, size: 10 };
  row.eachCell((cell) => {
    cell.fill = headerFill;
    cell.alignment = { vertical: "middle", wrapText: true };
    cell.border = { bottom: { style: "thin", color: { argb: "FFB6C4C1" } } };
  });
}

function addDataSheet(
  wb: ExcelJS.Workbook,
  name: string,
  widths: readonly number[],
  headers: readonly (string | number)[],
  rows: readonly (string | number | null)[][],
): void {
  const ws = wb.addWorksheet(name, {
    views: [{ state: "frozen", ySplit: 1 }],
    pageSetup: { orientation: "landscape", fitToPage: true, fitToWidth: 1, fitToHeight: 0 },
  });
  ws.columns = widths.map((w) => ({ width: Math.max(10, Math.round(w / 8)) }));
  const header = ws.addRow([...headers]);
  styleHeader(header);
  ws.pageSetup.printTitlesRow = "1:1";
  for (const r of rows) {
    ws.addRow(r).alignment = { vertical: "top", wrapText: true };
  }
}

/** Export trackers = the trackers the sheet carried (all three by default). */
const ALL_TRACKERS: readonly IaTracker[] = IA_TRACKERS;

