/** Professional pivot exports — PDF (vector text via jsPDF autoTable),
 *  Excel (.xlsx via ExcelJS with real styling) and CSV (UTF-8 BOM).
 *
 *  One shared model feeds every format so on-screen, PDF and Excel can never
 *  disagree: `buildExportTable()` maps a `PivotResult` into plain headers +
 *  rows with per-column roles (label / number / date / text) and keeps the
 *  subtotal / grand-total rows flagged for bolding.
 *
 *  Exports are print-ready by construction:
 *  - PDF: header row repeats on every page, rows never split, bold totals,
 *    footer "Page X of Y" + generated date, generated-by / district info.
 *    Landscape is chosen automatically when columns > 6.
 *  - Excel: Sheet "Report" (title, filters summary, styled table, freeze
 *    panes, auto-filter, real number formats, print setup + page footer),
 *    Sheet "Facility Data" (raw rows behind the report),
 *    Sheet "Report Info" (filters, generated by, timestamp).
 *  - CSV: UTF-8 with BOM (shared lib/pivot writer).
 *
 *  Kannada / Unicode: jsPDF's built-in Helvetica covers Latin only. Every
 *  PDF passes through `registerKannadaFont`, a single documented hook — drop
 *  a Noto Sans Kannada TTF in src/assets/fonts and register it there once;
 *  no other call site changes. */

