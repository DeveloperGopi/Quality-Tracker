export type ColumnRole = "label" | "number" | "date" | "text";

export interface ExportColumn {
  header: string;
  role: ColumnRole;
}

export interface ExportRow {
  /** Cells aligned 1:1 with `columns` — a label column ALWAYS gets an
   *  entry (body of a blank label level = null). Mostly generated as
   *  `columns.map(c => row[c.key])`. */
  cells: (string | number | null)[];
  kind: "leaf" | "subtotal" | "grand";
  /** Row-field depth of the source row (Excel outline levels). */
  depth?: number;
  /** For total rows: the LABEL-column index where the merged total label
   *  starts and how many label columns it spans (subtotal: from its own
   *  level to the last label column; grand: all). Null on leaf rows. */
  mergeFrom?: number;
  mergeSpan?: number;
  /** The merged label text ("Total — 2025" / "Grand Total"). */
  mergedLabel?: string | null;
}

export interface ExportMeta {
  title: string;
  subtitle: string;
  district: string;
  generatedBy: string;
  generatedAt: Date;
  /** Human list of applied filters, one string per filter field. */
  filters: string[];
  /** With a single value the measure name appears ONCE, in a caption line
   *  ("Values: Count of Facility") — not per header — matching the
   *  on-screen corner cell. */
  valuesCaption?: string | null;
}

export interface ExportTable {
  columns: ExportColumn[];
  rows: ExportRow[];
  meta: ExportMeta;
  /** Indices (into columns) whose cells are written as real numbers. */
  numericCols: number[];
}

/** Header wording identical to the on-screen measureLabel ("Count of
 *  Facility", "Average of Certified Score %"…) so exports always match the
 *  preview. */
function measureHeader(
  result: PivotResult,
  specIndex: number,
  comboIndex?: number,
): string {
  const spec = result.valueSpecs[specIndex];
  const field = result.valueFields[specIndex];
  const base = measureLabel(spec, field);
  if (comboIndex == null) return base;
  const combo = result.colCombos[comboIndex];
  const prefix =
    combo && combo.labels.length
      ? (combo.displayLabels ?? combo.labels).map((l) => l ?? "(No date)").join(" · ")
      : null;
  return prefix ? `${prefix} — ${base}` : base;
}

/** Excel/jsPDF role of one value column. Count, distinct, sum, average and
 *  % of total always produce numbers — even when counting a text field. */
function roleFor(
  agg: string,
  field: PivotResult["valueFields"][number],
): ColumnRole {
  if (
    agg === "pctTotal" ||
    agg === "count" ||
    agg === "distinct" ||
    agg === "sum" ||
    agg === "avg"
  )
    return "number";
  if (agg === "min" || agg === "max") {
    if (field?.type === "number") return "number";
    if (field?.type === "date") return "date";
  }
  return "text";
}

/** Map the on-screen pivot into the export model. Numbers stay numbers so
 *  Excel gets real numeric cells; dates become DD-MM-YYYY text.
 *
 *  ONE column model, shared with the on-screen preview (components/custom-
 *  report/PivotTable.buildPivotColumns):
 *  - the Grand Total column set is emitted ONLY when a column field exists
 *    (otherwise the row total duplicates the single value column),
 *  - a single value never repeats its measure name per column column:
 *    with one value the header IS the combo label (or the measure label
 *    when there is no column field); with 2+ values the header keeps the
 *    ``<combo> — <measure>`` two-level wording on one printed row. */
export function buildExportTable(
  result: PivotResult,
  meta: Omit<ExportMeta, "generatedAt"> & { generatedAt?: Date },
  opts?: {
    includeSubtotals?: boolean;
    includeGrandTotal?: boolean;
    /** Force the Grand Total column on/off (auto = only with a column field). */
    includeGrandColumn?: boolean;
  },
): ExportTable {
  const includeSubtotals = opts?.includeSubtotals ?? true;
  const includeGrandTotal = opts?.includeGrandTotal ?? true;
  const includeGrandColumn =
    opts?.includeGrandColumn ?? result.colFields.length > 0;
  const single = result.valueSpecs.length === 1;

  /* THE shared column model (same builder the screen table uses, so header
     i on screen = header i in Excel/PDF/CSV = cell i of every row). */
  const model = buildPivotColumns(result, { grandTotalColumn: includeGrandColumn });
  const labelCount = model.filter((c) => c.kind === "label").length;
  const columns: ExportColumn[] = model.map((c) => {
    if (c.kind === "label") {
      return { header: c.header, role: "label" as const };
    }
    if (c.kind === "value") {
      const v = c.valueIndex!;
      const spec = result.valueSpecs[v];
      return {
        header:
          single
            ? (comboPrefix(result, c.comboIndex!) ?? measureHeader(result, v))
            : measureHeader(result, v, c.comboIndex!),
        role: roleFor(spec.agg, result.valueFields[v]),
      };
    }
    // Grand Total column: "Grand Total" alone with one value — the value
    // label appears once, in the corner/caption; with 2+ values it carries
    // the per-value measure name.
    const v = c.valueIndex!;
    return {
      header: single ? "Grand Total" : `Grand Total — ${measureHeader(result, v)}`,
      role: roleFor(result.valueSpecs[v].agg, result.valueFields[v]),
    };
  });

  const valueCount = Math.max(result.valueSpecs.length, 1);
  const rows: ExportRow[] = [];
  for (const row of result.outRows) {
    if (row.kind === "subtotal" && !includeSubtotals) continue;
    if (row.kind === "grand" && !includeGrandTotal && rowFieldsExist(result)) continue;

    /* Cells are emitted PER COLUMN — never a positional short array — so a
       subtotal row can no longer start one column early (the previous
       implementation wrote one cell per EXISTING label and short rows
       shifted values into the wrong columns). */
    const cells: (string | number | null)[] =
      new Array(columns.length).fill(null);

    if (row.kind === "grand" && rowFieldsExist(result)) {
      // Grand Total row: the label merges across ALL row-label columns.
      cells[0] = "Grand Total";
      row.measures.forEach((cell, i) => {
        const m = labelCount + i;
        cells[m] = normalizeCell(cell, result.valueFields[Math.floor(i / valueCount)]);
      });
      if (includeGrandColumn)
        row.totals.forEach((cell, v) => {
          cells[labelCount + row.measures.length + v] = normalizeCell(
            cell,
            result.valueFields[v],
          );
        });
      rows.push({
        cells,
        kind: "grand",
        depth: 0,
        mergeFrom: 0,
        mergeSpan: labelCount,
        mergedLabel: "Grand Total",
      });
      continue;
    }

    // Leaf rows: one label cell per row-field level; blank below depth.
    // Subtotal rows: the parent levels carry their display labels and the
    // level's own label cell SEATS the "Total — <label>" caption and merges
    // across every label column from that level to the last one — the first
    // value cell therefore always lands under the FIRST value header.
    result.rowFields.forEach((_f, i) => {
      if (row.kind === "subtotal") {
        if (i === row.depth) {
          /* "Total — 2025" seats itself in the level's own label column —
             CSV/flat consumers read it right here, while Excel/PDF also get
             the merge span so it visually covers to the last label column. */
          cells[i] = `Total — ${row.displayLabels?.[row.depth] ?? row.labels[row.depth] ?? "(No date)"}`;
        } else if (i > row.depth) {
          cells[i] = null; // inside the merged span — plain blank, not "(blank)"
        } else {
          cells[i] = row.displayLabels?.[i] ?? row.labels[i] ?? "(blank)";
        }
        return;
      }
      const display = row.displayLabels?.[i] ?? row.labels[i];
      cells[i] = display ?? "(blank)";
    });
    row.measures.forEach((cell, i) => {
      const m = labelCount + i;
      cells[m] = normalizeCell(cell, result.valueFields[i % valueCount]);
    });
    if (includeGrandColumn)
      row.totals.forEach((cell, v) => {
        cells[labelCount + row.measures.length + v] = normalizeCell(
          cell,
          result.valueFields[v],
        );
      });

    rows.push({
      cells,
      kind: row.kind,
      depth: row.depth,
      ...(row.kind === "subtotal"
        ? (() => {
            const mergeFrom = row.depth;
            const mergeSpan = labelCount - row.depth;
            const label = `Total — ${row.displayLabels?.[row.depth] ?? row.labels[row.depth] ?? "(No date)"}`;
            // A single label column needs no merge — the text lands in the
            // label cell itself.
            if (mergeSpan <= 1) cells[mergeFrom] = label;
            return { mergeFrom, mergeSpan, mergedLabel: label };
          })()
        : {}),
    });
  }

  const numericCols: number[] = [];
  columns.forEach((c, i) => {
    if (c.role === "number") numericCols.push(i);
  });

  return {
    columns,
    rows,
    meta: {
      ...meta,
      generatedAt: meta.generatedAt ?? new Date(),
      valuesCaption:
        single && result.colFields.length > 0
          ? `Values: ${measureLabel(result.valueSpecs[0], result.valueFields[0])}`
          : null,
    },
    numericCols,
  };
}

/** The combo label of a column group ("Quality Certified"), or null when
 *  there is no column field. */
function comboPrefix(
  result: PivotResult,
  comboIndex: number,
): string | null {
  const combo = result.colCombos[comboIndex];
  if (!combo || combo.labels.length === 0) return null;
  return (combo.displayLabels ?? combo.labels).map((l) => l ?? "(No date)").join(" · ");
}

function rowFieldsExist(result: PivotResult): boolean {
  return result.rowFields.length > 0;
}

/** Dates keep their display format (DD-MM-YYYY); numbers stay raw. */
function normalizeCell(
  cell: string | number | null,
  field: PivotResult["valueFields"][number],
): string | number | null {
  if (cell == null) return null;
  if (typeof cell === "string" && /^\d{4}-\d{2}-\d{2}/.test(cell)) {
    const [y, m, d] = cell.slice(0, 10).split("-");
    return `${d}-${m}-${y}`;
  }
  if (field?.type === "date" && typeof cell === "string") return cell;
  return cell;
}

export const exportStamp = (d = new Date()) =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;

/** Number format contract: positive/negative grouping; zero prints as a
 *  muted "—" (a BLANK cell stays blank — a blank is never counted as 0;
 *  Excel only formats real zero values with the third section). Counts/sums
 *  use whole-number grouping; averages keep one decimal; % of Total keeps
 *  its % suffix. */
const IND_FORMAT = (header: string): string => {
  if (/% of Total/.test(header)) return '0.0\"%\";\"-\";\"—\"';
  if (/Average/.test(header)) return '#,##0.0;-#,##0.0;\"—\"';
  return '#,##0;-#,##0;\"—\"';
};

