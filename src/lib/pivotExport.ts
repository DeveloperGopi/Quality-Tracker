/** Professional vector-text PDF. Landscape automatically when columns > 6,
 *  all columns fit the page width, text wraps, header repeats per page,
 *  rows never split, totals bold, footer with page X of Y. */
/** A subtotal row must never sit ALONE at the top of a page. Pagination is
 *  deterministic, so it is planned on throwaway documents: any subtotal
 *  that would start a page gets bound to its preceding detail row by
 *  raising that row's minCellHeight (keep-with-previous) until both rows
 *  move to the next page together. Bounded loop guards pathological
 *  layouts; returns the map of extra minCellHeight per row. */
function planTotalGrouping(
  rows: { kind: ExportRow["kind"] }[],
  measure: (padding: Record<number, number>) => Set<number>,
): Record<number, number> {
  const padding: Record<number, number> = {};
  // The first measure pass runs with no padding.
  let topRows = measure(padding);
  for (let pass = 0; pass < 8 && topRows.size > 0; pass += 1) {
    let changed = false;
    for (const idx of [...topRows].sort((a, b) => a - b)) {
      const subtotal = rows[idx];
      const prev = rows[idx - 1];
      if (!subtotal || subtotal.kind !== "subtotal" || !prev || prev.kind !== "leaf")
        continue; // leaf+leaf or grand sequences are fine as they are
      padding[idx - 1] = (padding[idx - 1] ?? 0) + 26;
      changed = true;
    }
    if (!changed) break;
    topRows = measure(padding);
  }
  return padding;
}

/** Same layout contract as the screen (table-layout: fixed, widths from
 *  content): autoTable is given the SAME column order, and numeric columns
 *  get right alignment — header included (the header alignment equals the
 *  body alignment). */
function buildPdfBody(
  table: ExportTable,
): (string | { content: string; colSpan?: number; styles?: Record<string, unknown> })[][] {
  return table.rows.map((row) => {
    const out: (string | { content: string; colSpan?: number })[] = [];
    for (let i = 0; i < table.columns.length; i += 1) {
      const withinMerge =
        row.mergeFrom != null &&
        row.mergeSpan != null &&
        i > row.mergeFrom &&
        i < row.mergeFrom + row.mergeSpan;
      if (withinMerge) continue; // covered by the merged label cell
      const raw = row.cells[i];
      const text = raw == null ? "—" : String(raw);
      if (row.mergedLabel != null && i === row.mergeFrom && row.mergeSpan && row.mergeSpan > 1) {        out.push({ content: row.mergedLabel, colSpan: row.mergeSpan });
        i += row.mergeSpan - 1;
        continue;
      }
      out.push(text);
    }
    return out;
  });
}

export function exportPivotPdf(
  filename: string,
  table: ExportTable,
  opts?: {
    orientation?: "auto" | "portrait" | "landscape";
    pageSize?: "a4" | "a3" | "legal";
    marginsMm?: number;
    showPageNumbers?: boolean;
    includeFiltersSummary?: boolean;
    /** Optional top-groups bar chart, drawn as vector content above the
     *  table (Export settings → “Quick chart”). */
    chart?: { title: string; labels: string[]; values: number[] } | null;
  },
): void {
  const cols = table.columns.length;
  const orientation =
    !opts?.orientation || opts.orientation === "auto"
      ? cols > 6
        ? "landscape"
        : "portrait"
      : opts.orientation;
  const doc = new jsPDF({
    orientation,
    unit: "pt",
    format: opts?.pageSize ?? "a4",
  });
  registerKannadaFont(doc);

  const pageW = doc.internal.pageSize.getWidth();
  const margin = (opts?.marginsMm ?? 14) * 2.834;
  const usable = pageW - margin * 2;

  // Header block (page 1)
  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.setTextColor(...BRAND);
  doc.text(table.meta.title, margin, 38);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(90, 90, 90);
  let y = 52;
  doc.text(table.meta.subtitle, margin, y);
  y += 12;
  doc.text(
    `${table.meta.district} · Generated ${table.meta.generatedAt.toLocaleString()} · By ${table.meta.generatedBy}${table.meta.valuesCaption ? ` · ${table.meta.valuesCaption}` : ""}`,
    margin,
    y,
  );

  let startY = y + 18;
  if (opts?.includeFiltersSummary !== false && table.meta.filters.length > 0) {
    doc.setFontSize(8);
    doc.setTextColor(70, 70, 70);
    const lines = doc.splitTextToSize(
      `Filters: ${table.meta.filters.join(" · ") || "None"}`,
      usable,
    );
    doc.text(lines, margin, startY);
    startY += lines.length * 10 + 6;
  }

  // ---- vector bar chart (optional, top groups) ----
  if (opts?.chart && opts.chart.values.length > 0) {
    const chartDoc = doc;
    const { labels, values, title } = opts.chart;
    chartDoc.setFontSize(9);
    chartDoc.setTextColor(40, 40, 40);
    chartDoc.text(`Chart — ${title} (top groups)`, margin, startY + 8);
    const chartTop = startY + 16;
    const maxV = Math.max(...values, 1);
    const labelW = Math.min(110, usable * 0.3);
    const barMaxW = usable - labelW - 40;
    const barH = 11;
    const gap = 5;
    values.forEach((v, i) => {
      const yBar = chartTop + i * (barH + gap);
      const w = Math.max(2, (v / maxV) * barMaxW);
      chartDoc.setFontSize(7.5);
      chartDoc.setTextColor(60, 60, 60);
      const label = labels[i].length > 18 ? labels[i].slice(0, 17) + "…" : labels[i];
      chartDoc.text(label, margin, yBar + barH);
      chartDoc.setFillColor(...BRAND);
      chartDoc.rect(margin + labelW, yBar, w, barH, "F");
      chartDoc.setTextColor(30, 30, 30);
      chartDoc.text(
        v.toLocaleString("en-IN"),
        margin + labelW + w + 4,
        yBar + barH,
      );
    });
    startY = chartTop + values.length * (barH + gap) + 8;
  }

  const pdfBody = buildPdfBody(table);

  /* Layout options shared by the planning passes and the real draw pass —
     keeping them identical is what makes pagination deterministic. */
  const baseAtOptions = (paddedRows: Record<number, number>) => ({
    head: [table.columns.map((c) => c.header)],
    body: pdfBody,
    startY,
    margin: { left: margin, right: margin, top: 56 },
    styles: {
      fontSize: 7.4,
      cellPadding: 3.2,
      overflow: "linebreak" as const,
      valign: "middle" as const,
      lineColor: [214, 220, 218] as unknown as [number, number, number],
      lineWidth: 0.3,
      minCellHeight: 13,
    },
    headStyles: {
      fillColor: BRAND,
      textColor: 255,
      fontStyle: "bold" as const,
      fontSize: 7.6,
      halign: "center" as const,
      valign: "middle" as const,
      lineWidth: 0,
    },
    alternateRowStyles: { fillColor: [244, 248, 247] as unknown as [number, number, number] },
    columnStyles: table.columns.reduce<Record<number, { halign: "left" | "right" }>>(
      (acc, c, i) => {
        acc[i] = { halign: c.role === "number" ? "right" : "left" };
        return acc;
      },
      {},
    ),
    rowPageBreak: "avoid" as const, // a row is never split across pages
    showHead: "everyPage" as const, // header repeats on every page
    didParseCell: (data: CellHookData) => {
      if (data.section !== "body") return;
      const kind = table.rows[data.row.index]?.kind;
      if (kind === "subtotal") {
        data.cell.styles.fontStyle = "bold";
        data.cell.styles.fillColor = [233, 244, 242] as unknown as [number, number, number];        // the visual "thin top border" the style contract asks for
        data.cell.styles.lineWidth = {
          top: 0.6,
          left: 0.3,
          right: 0.3,
          bottom: 0.3,
        } as unknown as number;
      } else if (kind === "grand") {
        data.cell.styles.fontStyle = "bold";
        data.cell.styles.fillColor = [214, 234, 231] as unknown as [number, number, number];
      }
      // planned keep-with-previous padding (see planTotalGrouping)
      const pad = paddedRows[data.row.index];
      if (pad) data.cell.styles.minCellHeight += pad;
    },
  });

  /* A subtotal row must never sit ALONE at the top of a page: pagination is
     deterministic, so it is PLANNED on throwaway documents first. Any
     subtotal that would start a page gets bound to its preceding detail
     row by raising that row's minCellHeight until both rows move to the
     next page together (bounded loop for pathological layouts). */
  const paddedRows = planTotalGrouping(table.rows, (padding) => {
    const scratch = new jsPDF({
      orientation,
      unit: "pt",
      format: opts?.pageSize ?? "a4",
    });
    const topRows = new Set<number>();
    const seenPages = new Set<number>();
    autoTable(scratch, {
      ...baseAtOptions(padding),
      didDrawCell: (data: CellHookData) => {
        if (data.section !== "body" || !data.pageNumber) return;
        if (!seenPages.has(data.pageNumber)) {
          seenPages.add(data.pageNumber);
          topRows.add(data.row.index);
        }
      },
    });
    return topRows;
  });

  autoTable(doc, {
    ...baseAtOptions(paddedRows),
    didDrawPage: (data) => {
      const pageH = doc.internal.pageSize.getHeight();
      const no = data.pageNumber ?? 1;
      // continuation pages re-draw a compact title
      if (no > 1) {
        doc.setFont("helvetica", "bold");
        doc.setFontSize(11);
        doc.setTextColor(...BRAND);
        doc.text(table.meta.title, margin, 30);
        doc.setFont("helvetica", "normal");
        doc.setFontSize(9);
        doc.setTextColor(90, 90, 90);
      }
      // footer: brand · date · page number
      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.setTextColor(120, 120, 120);
      const footY = pageH - 18;
      doc.text("NQAS Tracker", margin, footY);
      doc.text(table.meta.generatedAt.toLocaleString(), pageW / 2, footY, {
        align: "center",
      });
      if (opts?.showPageNumbers !== false)
        doc.text(`Page ${no}`, pageW - margin, footY, { align: "right" });
    },
  });

  doc.save(filename);
}

