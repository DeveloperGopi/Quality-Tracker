/** Full .xlsx export via ExcelJS — three sheets, print-ready. */
export async function exportPivotExcel(
  filename: string,
  table: ExportTable,
  raw: { headers: string[]; cells: (string | number | null)[][] },
  opts?: {
    pageSize?: "a4" | "a3" | "legal";
    orientation?: "portrait" | "landscape";
    includeFacilityDataSheet?: boolean;
  },
): Promise<void> {
  const wb = new ExcelJS.Workbook();
  wb.creator = table.meta.generatedBy;
  wb.created = table.meta.generatedAt;

  /* ------------------------- Sheet 1: Report ------------------------- */
  const labelCount = table.columns.filter((c) => c.role === "label").length;
  const valueCount = Math.max(
    table.columns.filter((c) => c.header.startsWith("Grand Total")).length ||
      table.columns.length - labelCount,
    1,
  );
  const width = Math.max(table.columns.length, 2);
  const ws = wb.addWorksheet("Report", {
    views: [{ state: "frozen", xSplit: labelCount, ySplit: 5 }],
    pageSetup: {
      paperSize: (opts?.pageSize === "a3"
        ? 8
        : opts?.pageSize === "legal"
          ? 5
          : 9) as never,
      orientation: opts?.orientation ?? "landscape",
      fitToPage: true,
      fitToWidth: 1,
      fitToHeight: 0,
      horizontalCentered: true,
    },
  });

  const merge = (row: number, text: string, font?: Partial<ExcelJS.Font>) => {
    ws.mergeCells(row, 1, row, width);
    const cell = ws.getCell(row, 1);
    cell.value = text;
    if (font) cell.font = { size: 10, ...font } as ExcelJS.Font;
    return cell;
  };

  merge(1, table.meta.title, {
    bold: true,
    size: 16,
    color: { argb: ARB.brand },
  });
  merge(2, `${table.meta.subtitle} · ${table.meta.district}${table.meta.valuesCaption ? ` · ${table.meta.valuesCaption}` : ""}`, {
    color: { argb: ARB.grey },
  });
  merge(
    3,
    `Generated by ${table.meta.generatedBy} on ${table.meta.generatedAt.toLocaleString()}`,
    { color: { argb: ARB.grey } },
  );

  let rowNow = 4;
  if (table.meta.filters.length > 0) {
    const c = merge(4, `Filters: ${table.meta.filters.join(" · ")}`, {
      italic: true,
      color: { argb: "FF374151" },
    });
    c.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: ARB.subtotalRow },
    };
    rowNow = 5;
  }
  const headerRowIndex = rowNow + 1; // leave one spacer row

  const header = ws.getRow(headerRowIndex);
  header.values = table.columns.map((c) => c.header);
  header.height = 30;
  header.eachCell((cell, col) => {
    const role = table.columns[col - 1]?.role;
    cell.font = { bold: true, size: 10, color: { argb: "FFFFFFFF" } };
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: ARB.brand } };
    /* Header alignment equals body alignment: numeric headers align right
       with their right-aligned figures, labels left, dates centre. */
    cell.alignment = {
      vertical: "middle",
      wrapText: true,
      horizontal:
        role === "number" ? "right" : role === "date" ? "center" : "left",
    };
    cell.border = { top: thin, bottom: thin, left: thin, right: thin };
  });

  /* body */
  /** Sheet row of the first + last data row of a total row's group. With
   *  SUBTOTAL(9) the nested ranges are safe: SUM ignores nested SUBTOTAL
   *  results, so a year total over leaves+month subtotals is right and the
   *  grand total over the whole sheet never double-counts. */
  const groupRange = (rows: ExportRow[], i: number): [number, number] | null => {
    const row = rows[i];
    const depth =
      row.kind === "grand" ? 0 : row.mergeFrom ?? 0;
    if (i === 0) return null;
    let j = i - 1;
    let start = i - 1;
    while (j >= 0) {
      const cand = rows[j];
      if (cand.kind === "grand") break;
      const sameSubtree =
        depth === 0 ||
        cellsEqual(cand.cells.slice(0, depth), row.cells.slice(0, depth));
      if (!sameSubtree) break;
      start = j;
      j -= 1;
    }
    if (i === 0 || start >= i) return null;
    return [start, i - 1];
  };
  const cellsEqual = (a: (string | number | null)[], b: (string | number | null)[]) =>
    a.length === b.length && a.every((v, k2) => (v ?? null) === (b[k2] ?? null));
  const isPlainSum = (header: string) => !/Average|% of Total/.test(header);

  table.rows.forEach((row, idx) => {
    const r = ws.getRow(headerRowIndex + 1 + idx);
    // Value + style every cell first — merged cells keep the styling.
    row.cells.forEach((c, k) => {
      const cell = r.getCell(k + 1);
      if (c != null) cell.value = c as ExcelJS.CellValue;
    });
    const isTotal = row.kind !== "leaf";
    for (let col = 1; col <= width; col += 1) {
      const cell = r.getCell(col);
      const column = table.columns[col - 1];
      cell.border = isTotal
        ? {
            top: thin,
            bottom: row.kind === "grand" ? thin : { style: "hair", color: { argb: ARB.hair } },
            left: { style: "hair", color: { argb: ARB.hair } },
            right: { style: "hair", color: { argb: ARB.hair } },
          }
        : cellBorder;
      cell.alignment = {
        vertical: "middle",
        wrapText: true,
        horizontal:
          column?.role === "number" ? "right" : column?.role === "date" ? "center" : "left",
      };
      if (column?.role === "number" && typeof cell.value === "number")
        cell.numFmt = IND_FORMAT(column.header);
      if (isTotal) {
        // the WHOLE total row — every cell, not only numeric ones
        cell.font =
          row.kind === "grand"
            ? { bold: true, size: 10, color: { argb: "FFFFFFFF" } }
            : { bold: true, size: 10 };
        cell.fill = {
          type: "pattern",
          pattern: "solid",
          fgColor: { argb: row.kind === "grand" ? ARB.grandRow : ARB.subtotalRow },
        };
      } else if (idx % 2 === 1) {
        cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: ARB.band } };
      }
    }

    // Merged total label: the caption sits in the LEVEL's label column and
    // spans every row-label column from that level to the last one, so the
    // first value cell always lands under the first value header.
    if ((row.mergeFrom ?? 0) < labelCount) {
      const col = (row.mergeFrom ?? 0) + 1;
      if ((row.mergeSpan ?? 1) > 1) {
        ws.mergeCells(headerRowIndex + 1 + idx, col, headerRowIndex + 1 + idx, labelCount);
        if (row.mergedLabel != null)
          r.getCell(col).value = row.mergedLabel;
      }
    }

    // Outline levels: every row folds under the group that follows it (the
    // summary row sits BELOW its detail), so the user can collapse each
    // year / block straight from Excel.
    if (row.kind === "leaf") {
      const depth = row.depth ?? 0;
      r.outlineLevel = Math.min(depth + 1, 8);
    } else if (row.kind === "subtotal") {
      const depth = row.mergeFrom ?? 0;
      r.outlineLevel = Math.min(depth, 8);
    }

    // Live formulas with cached results:
    //  • subtotal/grand rows: SUBTOTAL(9, group range)  — nested subtotals
    //    are ignored by Excel, so nothing is ever double-counted;
    //  • the Grand Total column in a total row: SUM across that row's
    //    per-combo value cells — the column never renders empty.
    if (isTotal) {
      const range = groupRange(table.rows, idx);
      table.numericCols.forEach((c) => {
        const raw = row.cells[c];
        if (typeof raw !== "number") return;
        const head = table.columns[c].header;
        if (!isPlainSum(head)) return;
        const cell = r.getCell(c + 1);
        if (row.kind === "grand") {
          if (range) {
            cell.value = {
              formula: `SUBTOTAL(9,${ws.getCell(headerRowIndex + 1 + range[0], c + 1).address}:${ws.getCell(headerRowIndex + 1 + range[1], c + 1).address})`,
              result: raw,
            };
          }
        } else {
          const grandColStart = table.columns.findIndex(
            (col, k) => k >= labelCount && col.header.startsWith("Grand Total"),
          );
          const isGrandCol = grandColStart >= 0 && c >= grandColStart;
          if (isGrandCol) {
            // Grand Total COLUMN of a total row: SUM across that row's
            // per-combo value cells for the same value spec — the column
            // never renders empty.
            const v = c - grandColStart;
            const addr: string[] = [];
            const comboCount = Math.max(
              Math.floor(
                (grandColStart - labelCount) / Math.max(valueCount, 1),
              ),
              1,
            );
            for (let combo = 0; combo < comboCount; combo += 1) {
              addr.push(
                ws.getCell(
                  headerRowIndex + 1 + idx,
                  labelCount + combo * valueCount + v + 1,
                ).address,
              );
            }
            if (addr.length > 1)
              cell.value = { formula: `SUM(${addr.join(",")})`, result: raw };
          } else if (range) {
            cell.value = {
              formula: `SUBTOTAL(9,${ws.getCell(headerRowIndex + 1 + range[0], c + 1).address}:${ws.getCell(headerRowIndex + 1 + range[1], c + 1).address})`,
              result: raw,
            };
          }
        }
      });
    }
  });

  ws.autoFilter = {
    from: { row: headerRowIndex, column: 1 },
    to: { row: headerRowIndex + table.rows.length, column: width },
  };

  // Auto-fit widths (header counts ~half because they wrap)
  table.columns.forEach((column, col) => {
    let longest = column.header.length / 2 + 2;
    for (const row of table.rows) {
      const v = row.cells[col];
      const len = v == null ? 0 : String(v).length;
      if (len > longest) longest = len;
    }
    ws.getColumn(col + 1).width = Math.min(46, Math.max(9, Math.round(longest + 2)));
  });

  ws.headerFooter = {
    oddFooter: `&L NQAS Tracker &C Generated ${exportStamp(table.meta.generatedAt)} &R Report ID ${reportIdOf(table)} · Page &P of &N`,
  };
  if (width >= 2) {
    ws.pageSetup.margins = {
      left: 0.4,
      right: 0.4,
      top: 0.6,
      bottom: 0.6,
      header: 0.2,
      footer: 0.2,
    } as ExcelJS.PageSetup["margins"];
  }

  /* --------------------- Sheet 2: Facility Data ---------------------- */
  if (opts?.includeFacilityDataSheet !== false && raw.cells.length > 0) {
    const wsRaw = wb.addWorksheet("Facility Data", {
      views: [{ state: "frozen", ySplit: 1 }],
      pageSetup: { orientation: "landscape", fitToPage: true, fitToWidth: 1 },
    });
    const hr = wsRaw.getRow(1);
    hr.values = raw.headers;
    hr.font = { bold: true, size: 10, color: { argb: "FFFFFFFF" } };
    hr.fill = { type: "pattern", pattern: "solid", fgColor: { argb: ARB.brand } };
    hr.alignment = { vertical: "middle", wrapText: true, horizontal: "center" };
    hr.height = 24;
    raw.cells.forEach((cells, i) => {
      wsRaw.getRow(i + 2).values = cells.map((c) => (c == null ? "" : c)) as ExcelJS.CellValue[];
    });
    raw.headers.forEach((h, i) => {
      let longest = h.length;
      for (const cells of raw.cells) {
        const len = String(cells[i] ?? "").length;
        if (len > longest) longest = len;
      }
      wsRaw.getColumn(i + 1).width = Math.min(40, Math.max(9, longest + 2));
    });
    wsRaw.autoFilter = {
      from: { row: 1, column: 1 },
      to: { row: 1 + raw.cells.length, column: Math.max(raw.headers.length, 1) },
    };
  }

  /* ----------------------- Sheet 3: Report Info ---------------------- */
  const wsInfo = wb.addWorksheet("Report Info", {
    pageSetup: { orientation: "portrait", fitToPage: true, fitToWidth: 1 },
  });
  wsInfo.columns = [{ width: 28 }, { width: 90 }];
  const infoRows: [string, string][] = [
    ["Report title", table.meta.title],
    ["Subtitle", table.meta.subtitle],
    ["District", table.meta.district],
    ["Generated by", table.meta.generatedBy],
    ["Generated at", table.meta.generatedAt.toLocaleString()],
    ["Facilities in scope", String(raw.cells.length)],
    ["Report rows", String(table.rows.length)],
    ["Columns", String(table.columns.length)],
    ...table.meta.filters.map(
      (flt, i): [string, string] => [`Filter ${i + 1}`, flt],
    ),
  ];
  infoRows.forEach(([k, v], i) => {
    const row = wsInfo.getRow(i + 1);
    row.getCell(1).value = k;
    row.getCell(1).font = { bold: true, size: 10 };
    row.getCell(2).value = v;
    row.getCell(2).font = { size: 10 };
    row.getCell(2).alignment = { wrapText: true, vertical: "top" };
  });

  const buffer = await wb.xlsx.writeBuffer();
  downloadBlob(
    new Blob([buffer], { type: "application/octet-stream" }),
    filename,
  );
}

function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

/** Stable short report id printed in the Excel footer
 *  ("Report ID 2026-05-31-1432"). */
function reportIdOf(table: ExportTable): string {
  const d = table.meta.generatedAt;
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}-${pad(d.getHours())}${pad(d.getMinutes())}`;
}

