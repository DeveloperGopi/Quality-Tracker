/**
 * PENDING & FOLLOW-UP EXPORTS — the same rows, reasons and remarks the screen
 * shows. Excel follows the Line-list conventions (cover, summary, frozen
 * header + Facility, AutoFilter, wrapped text, status colours with text,
 * dates DD-MMM-YYYY, print setup); PDF uses the shared embedded Noto Sans /
 * Noto Sans Tamil faces and repeats the header on every page; CSV carries the
 * UTF-8 BOM so Tamil remarks and ₹ open correctly in Excel.
 *
 * The file name is `{District} Pending and Attention List {DD-MM-YYYY}`.
 * Exports are always built from the CALLER's filtered rows, so the numbers on
 * screen and in the file are the same calculation.
 */

import type { Workbook } from "exceljs";
import type { jsPDF } from "jspdf";
import { ORG_NAME, ORG_SIGNATURE } from "@/lib/org";
import {
  ISSUE_CATEGORY_LABEL,
  ISSUE_SEVERITY_LABEL,
  ISSUE_STATUS_LABEL,
  dmy,
  pendingCounts,
  type PendingIssueRow,
} from "@/lib/pending";

export type PendingExportMeta = {
  district: string;
  filtersText: string;
  generatedBy: string;
  /** DD-MMM-YYYY — also the "Data as of" line. */
  dataAsOf: string;
  /** `{District} Pending and Attention List {DD-MM-YYYY}` (no extension). */
  fileNameBase: string;
};

export type PendingExportResult = { fileName: string; rows: number };

const COVER_FILL = "FF1F4E3D";
const HEADER_FILL = "FF1F4E3D";
const ZEBRA_FILL = "FFF4F8F7";

const STATUS_FILL: Record<string, string> = {
  Open: "FFFEF3C7",
  "In progress": "FFE0F2FE",
  Snoozed: "FFEDE9FE",
  Resolved: "FFD1FAE5",
};
const SEVERITY_FILL: Record<string, string> = {
  High: "FFFFE4E6",
  Medium: "FFFEF3C7",
  Low: "FFF1F5F9",
};

function downloadBlob(fileName: string, blob: Blob) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  a.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 30_000);
}

const orDash = (value: string | null | undefined) => (value && value.trim() ? value : "-");

